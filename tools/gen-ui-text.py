def c_literal(text):
    out = []
    prev_hex = False
    for b in text.encode('utf-8'):
        ch = chr(b)
        if b >= 0x80:
            out.append('\\x%02X' % b)
            prev_hex = True
            continue
        # A hex escape swallows the hex digits after it: split the literal.
        if prev_hex and ch in '0123456789abcdefABCDEF':
            out.append('" "')
        out.append('\\' + ch if ch in '"\\' else ch)
        prev_hex = False
    return '"' + ''.join(out) + '"'


def write(name, lines):
    with open(os.path.join(UI_DIR, name), 'w', encoding='ascii', newline='\n') as f:
        f.write("\n".join(lines) + "\n")


